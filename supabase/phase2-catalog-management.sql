-- 1. Nuevos campos sin borrar datos existentes.
alter table public.products add column if not exists subcategory text;
alter table public.products add column if not exists image_urls text[] not null default '{}'::text[];
create index if not exists products_subcategory_idx on public.products (subcategory);

-- 2. Registro central de subcategorías: NO se crea una tabla por cada etiqueta.
create table if not exists public.catalog_subcategories (
  id bigint generated by default as identity primary key,
  name text not null,
  name_key text generated always as (lower(btrim(name))) stored unique,
  created_at timestamptz not null default now()
);
alter table public.catalog_subcategories enable row level security;
grant select on public.catalog_subcategories to anon, authenticated;
drop policy if exists "Public can read catalog subcategories" on public.catalog_subcategories;
create policy "Public can read catalog subcategories" on public.catalog_subcategories for select to anon, authenticated using (true);
create or replace function public.register_catalog_subcategory()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.subcategory := nullif(btrim(new.subcategory), '');
  if new.subcategory is not null then
    insert into public.catalog_subcategories (name) values (new.subcategory) on conflict (name_key) do nothing;
  end if;
  return new;
end; $$;
drop trigger if exists products_register_subcategory on public.products;
create trigger products_register_subcategory before insert or update of subcategory on public.products for each row execute function public.register_catalog_subcategory();
insert into public.catalog_subcategories (name) select distinct btrim(subcategory) from public.products where nullif(btrim(subcategory), '') is not null on conflict (name_key) do nothing;

-- 3. Términos y condiciones editables desde el inventario.
create table if not exists public.catalog_terms (
  id integer primary key default 1 check (id = 1),
  title text not null default 'Términos y condiciones',
  content text not null default '',
  updated_at timestamptz not null default now()
);
alter table public.catalog_terms enable row level security;
grant select, insert, update on public.catalog_terms to anon, authenticated;
drop policy if exists "Public can read catalog terms" on public.catalog_terms;
drop policy if exists "Authenticated users can manage catalog terms" on public.catalog_terms;
drop policy if exists "Demo inventory can manage catalog terms" on public.catalog_terms;
create policy "Public can read catalog terms" on public.catalog_terms for select to anon, authenticated using (true);
-- La app de inventario actual usa identificación por nombre, no Supabase Auth.
-- Esta política de DEMO permite que su clave publicable guarde los términos. No es segura para un sitio comercial público.
create policy "Demo inventory can manage catalog terms" on public.catalog_terms for all to anon, authenticated using (true) with check (true);
create or replace function public.set_catalog_terms_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at = now(); return new; end; $$;
drop trigger if exists catalog_terms_updated_at on public.catalog_terms;
create trigger catalog_terms_updated_at before update on public.catalog_terms for each row execute function public.set_catalog_terms_updated_at();
insert into public.catalog_terms (id,title,content) values (1,'Términos y condiciones','1. Disponibilidad de productos\nLa disponibilidad puede cambiar; confirma antes del pago.\n\n2. Precios\nLos precios deben confirmarse al gestionar el pedido.\n\n3. Pedidos\nEnviar una consulta no reserva automáticamente un producto.\n\n4. Imágenes y descripciones\nLas fotografías son referenciales y puede haber pequeñas variaciones.') on conflict (id) do nothing;

-- 4. Métricas aproximadas: un registro por navegador (ID aleatorio guardado localmente).
create table if not exists public.catalog_visitors (
  visitor_id text primary key,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  last_visit_date date not null default current_date
);
alter table public.catalog_visitors enable row level security;
revoke all on public.catalog_visitors from anon, authenticated;

create or replace function public.register_catalog_presence(p_visitor_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare result jsonb;
begin
  if p_visitor_id is null or length(p_visitor_id) < 8 or length(p_visitor_id) > 120 then
    raise exception 'Identificador de visitante no válido';
  end if;
  insert into public.catalog_visitors(visitor_id, first_seen_at, last_seen_at, last_visit_date)
  values (p_visitor_id, now(), now(), current_date)
  on conflict (visitor_id) do update set last_seen_at = now(), last_visit_date = current_date;
  select jsonb_build_object(
    'total_visitors', (select count(*) from public.catalog_visitors),
    'visitors_today', (select count(*) from public.catalog_visitors where last_visit_date = current_date),
    'online_now', (select count(*) from public.catalog_visitors where last_seen_at > now() - interval '90 seconds')
  ) into result;
  return result;
end;
$$;
revoke all on function public.register_catalog_presence(text) from public;
grant execute on function public.register_catalog_presence(text) to anon, authenticated;

create or replace function public.get_catalog_metrics()
returns jsonb language sql security definer set search_path = public as $$
  select jsonb_build_object(
    'total_visitors', (select count(*) from public.catalog_visitors),
    'visitors_today', (select count(*) from public.catalog_visitors where last_visit_date = current_date),
    'online_now', (select count(*) from public.catalog_visitors where last_seen_at > now() - interval '90 seconds')
  );
$$;
revoke all on function public.get_catalog_metrics() from public;
grant execute on function public.get_catalog_metrics() to anon, authenticated;

