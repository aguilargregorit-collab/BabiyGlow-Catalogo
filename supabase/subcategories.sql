-- Babi&Glow: subtipos dinámicos para los productos del catálogo.
-- Ejecutar UNA VEZ en Supabase > SQL Editor, en el mismo proyecto usado por el inventario.
-- El inventario guardará la etiqueta elegida en products.subcategory.
-- No se crea una tabla nueva por subtipo: catalog_subcategories registra cada etiqueta automáticamente.

-- 1) Añade la etiqueta opcional al registro del producto sin modificar los productos existentes.
alter table public.products
  add column if not exists subcategory text;

create index if not exists products_subcategory_idx
  on public.products (subcategory);

-- 2) Registro central de nombres de subcategoría. La clave normalizada evita duplicados
-- como "Bodys", "bodys" y "BODYS".
create table if not exists public.catalog_subcategories (
  id bigint generated by default as identity primary key,
  name text not null,
  name_key text generated always as (lower(btrim(name))) stored unique,
  created_at timestamptz not null default now()
);

alter table public.catalog_subcategories enable row level security;
grant select on public.catalog_subcategories to anon, authenticated;

drop policy if exists "Public can read catalog subcategories" on public.catalog_subcategories;
create policy "Public can read catalog subcategories"
  on public.catalog_subcategories
  for select
  to anon, authenticated
  using (true);

-- 3) Cada vez que el inventario guarda una etiqueta, se normaliza y registra automáticamente.
-- SECURITY DEFINER permite que el trigger registre el nombre sin abrir permisos de escritura
-- directos sobre la tabla de subcategorías para visitantes del catálogo.
create or replace function public.register_catalog_subcategory()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.subcategory := nullif(btrim(new.subcategory), '');

  if new.subcategory is not null then
    insert into public.catalog_subcategories (name)
    values (new.subcategory)
    on conflict (name_key) do nothing;
  end if;

  return new;
end;
$$;

drop trigger if exists products_register_subcategory on public.products;
create trigger products_register_subcategory
before insert or update of subcategory on public.products
for each row
execute function public.register_catalog_subcategory();

-- 4) Registra también las etiquetas que ya existan antes de instalar esta función.
insert into public.catalog_subcategories (name)
select distinct btrim(subcategory)
from public.products
where nullif(btrim(subcategory), '') is not null
on conflict (name_key) do nothing;

-- 5) Garantiza que los cambios de etiqueta puedan llegar al catálogo por Realtime.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'products'
  ) then
    alter publication supabase_realtime add table public.products;
  end if;
end $$;
